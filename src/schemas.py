"""src/schemas.py

Pydantic data models and schemas defining data contracts across the pipeline.
Includes schemas for raw log records, normalized events, alert classifications,
SHAP feature attributions, and GenAI incident triage summaries.
"""

import json
import re
from typing import Any, Dict, List, Literal, Optional, Union
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

# Allowed threat categories strictly restricted to the specified list
ThreatCategory = Literal[
    "Brute Force",
    "Privilege Escalation",
    "Lateral Movement",
    "Command and Control",
    "Exfiltration",
    "Execution",
    "Unknown / Insufficient Data",
]

ALLOWED_THREAT_CATEGORIES: set[str] = {
    "Brute Force",
    "Privilege Escalation",
    "Lateral Movement",
    "Command and Control",
    "Exfiltration",
    "Execution",
    "Unknown / Insufficient Data",
}

# Allowed evidence status
EvidenceStatus = Literal["Sufficient", "Insufficient Data"]
ALLOWED_EVIDENCE_STATUSES: set[str] = {"Sufficient", "Insufficient Data"}


class IncidentAnalysisReport(BaseModel):
    """Pydantic-validated incident analysis report generated by the GenAI triage module.

    Data contract requires exactly these fields:
    - evidence_status: 'Sufficient' or 'Insufficient Data'
    - incident_summary: Human-readable narrative of the security event
    - threat_category: Restricted to predefined threat classifications
    - mitre_attack_id: Associated MITRE ATT&CK technique identifier or None
    - recommended_actions: Non-executable mitigation recommendations
    """

    model_config = ConfigDict(extra="forbid")

    evidence_status: EvidenceStatus = Field(
        ...,
        description="Confidence status of available evidence ('Sufficient' or 'Insufficient Data')",
    )
    incident_summary: str = Field(
        ...,
        description="Factual narrative summarizing log evidence and SHAP feature contributions",
    )
    threat_category: ThreatCategory = Field(
        ...,
        description="Classified threat category from the allowed taxonomy",
    )
    mitre_attack_id: Optional[str] = Field(
        default=None,
        description="MITRE ATT&CK technique ID (e.g., 'T1110') if evidence is sufficient, else None",
    )
    recommended_actions: List[str] = Field(
        default_factory=list,
        description="Advisory triage and remediation recommendations (never auto-executed)",
    )

    @field_validator("incident_summary")
    @classmethod
    def validate_incident_summary(cls, v: str) -> str:
        """Ensures incident_summary is non-empty, non-whitespace, and within safe length limits."""
        if not isinstance(v, str) or not v.strip():
            raise ValueError("incident_summary must be a non-empty narrative string")
        v_stripped = v.strip()
        if len(v_stripped) > 20000:
            return v_stripped[:20000] + "... [TRUNCATED DUE TO SIZE]"
        return v_stripped

    @field_validator("recommended_actions", mode="before")
    @classmethod
    def parse_recommended_actions_before(cls, v: Any) -> Any:
        """Allows deserialization of JSON-encoded array strings and normalizes action items."""
        if isinstance(v, str):
            v_stripped = v.strip()
            if v_stripped.startswith("[") and v_stripped.endswith("]"):
                try:
                    parsed = json.loads(v_stripped)
                    if isinstance(parsed, list):
                        v = parsed
                except json.JSONDecodeError:
                    pass
        if isinstance(v, list):
            cleaned: List[str] = []
            for item in v:
                if isinstance(item, str):
                    item_clean = item.strip()
                    if item_clean:
                        cleaned.append(item_clean[:500])
                else:
                    item_clean = str(item).strip()
                    if item_clean:
                        cleaned.append(item_clean[:500])
            if len(cleaned) > 50:
                cleaned = cleaned[:50]
            return cleaned
        return v

    @field_validator("mitre_attack_id", mode="before")
    @classmethod
    def validate_and_normalize_mitre_id(cls, v: Any) -> Optional[str]:
        """Normalizes and validates MITRE ATT&CK technique identifier syntactic format.

        Supports techniques (e.g., 'T1110') and sub-techniques (e.g., 'T1059.001').
        Uses strict ASCII matching to reject Unicode digit lookalikes.
        Note: Validates syntactic format; does not query an external MITRE STIX knowledge base.
        """
        if v is None:
            return None
        if isinstance(v, str):
            v_stripped = v.strip()
            if not v_stripped or v_stripped.lower() in ("none", "null", "n/a", "unknown"):
                return None
            if not re.match(r"^[Tt][0-9]{4}(\.[0-9]{3})?$", v_stripped, re.ASCII):
                raise ValueError(
                    f"Invalid mitre_attack_id '{v_stripped}'. Must follow standard ASCII MITRE ATT&CK format (e.g., 'T1110' or 'T1110.001')"
                )
            return v_stripped.upper()
        raise ValueError(f"mitre_attack_id must be a string or None, got {type(v).__name__}")

    @field_validator("threat_category")
    @classmethod
    def validate_category_allowed(cls, v: str) -> str:
        if v not in ALLOWED_THREAT_CATEGORIES:
            raise ValueError(
                f"Invalid threat_category '{v}'. Must be one of: {sorted(ALLOWED_THREAT_CATEGORIES)}"
            )
        return v

    @model_validator(mode="after")
    def validate_evidence_consistency(self) -> "IncidentAnalysisReport":
        """Enforces schema consistency between evidence status, threat category, MITRE ID, and actions.

        Rules:
        - When evidence_status is 'Insufficient Data':
          - threat_category MUST be 'Unknown / Insufficient Data'
          - mitre_attack_id MUST be None
          - recommended_actions MUST be empty []
        - When evidence_status is 'Sufficient':
          - threat_category CANNOT be 'Unknown / Insufficient Data'
        """
        if self.evidence_status == "Insufficient Data":
            if self.threat_category != "Unknown / Insufficient Data":
                raise ValueError(
                    f"When evidence_status is 'Insufficient Data', threat_category must be "
                    f"'Unknown / Insufficient Data', got '{self.threat_category}'"
                )
            if self.mitre_attack_id is not None:
                raise ValueError(
                    f"When evidence_status is 'Insufficient Data', mitre_attack_id must be None, "
                    f"got '{self.mitre_attack_id}'"
                )
            if len(self.recommended_actions) > 0:
                raise ValueError(
                    f"When evidence_status is 'Insufficient Data', recommended_actions must be empty, "
                    f"got {self.recommended_actions}"
                )
        elif self.evidence_status == "Sufficient":
            if self.threat_category == "Unknown / Insufficient Data":
                raise ValueError(
                    "When evidence_status is 'Sufficient', threat_category cannot be "
                    "'Unknown / Insufficient Data'"
                )
        return self


# Backward-compatible alias
IncidentTriageSummary = IncidentAnalysisReport


class IncidentTriageInput(BaseModel):
    """Input payload container for triage analysis."""

    model_config = ConfigDict(extra="ignore", arbitrary_types_allowed=True)

    classifier_prediction: Optional[Union[str, int, float, Dict[str, Any], Any]] = None
    risk_score: Optional[float] = None
    threshold: Optional[float] = None
    feature_values: Optional[Any] = Field(default_factory=dict)
    shap_contributions: Optional[Any] = Field(default_factory=dict)
    log_evidence: Optional[Any] = None

    @field_validator("risk_score", "threshold", mode="before")
    @classmethod
    def validate_score_range(cls, v: Any) -> Optional[float]:
        """Validates that risk_score and threshold are numeric floats between 0.0 and 1.0 (rejects booleans, NaN, Inf)."""
        if v is None:
            return None
        if isinstance(v, bool) or type(v).__name__ in ("bool", "bool_"):
            raise ValueError(f"Score cannot be a boolean value, got '{v}'")
        if hasattr(v, "item") and callable(getattr(v, "item")):
            try:
                extracted = v.item()
            except Exception:
                extracted = v
            if isinstance(extracted, bool) or type(extracted).__name__ in ("bool", "bool_"):
                raise ValueError(f"Score cannot be a boolean value, got '{v}'")
            v = extracted
        try:
            val = float(v)
        except (ValueError, TypeError) as exc:
            raise ValueError(f"Score must be a valid numeric float, got '{v}'") from exc
        if val != val or val in (float("inf"), float("-inf")):
            raise ValueError(f"Score cannot be NaN or Infinite, got '{v}'")
        if not (0.0 <= val <= 1.0):
            raise ValueError(f"Score must be between 0.0 and 1.0 inclusive, got {val}")
        return val

    @field_validator("shap_contributions", "feature_values", mode="before")
    @classmethod
    def convert_series_or_mapping_to_dict(cls, v: Any) -> Any:
        """Converts pandas Series or mapping objects to dict."""
        if hasattr(v, "to_dict") and callable(getattr(v, "to_dict")):
            try:
                return v.to_dict()
            except Exception:
                pass
        return v
